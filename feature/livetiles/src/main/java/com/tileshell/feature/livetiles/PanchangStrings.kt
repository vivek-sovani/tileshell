        /** [month] is 0 for January, as `Calendar.MONTH`. */
        fun gregorianMonth(language: PanchangLanguage, month: Int): String = MONTHS[language.ordinal][month]

        /** The word that closes a 12-hour time (or its short form where a tile is one column wide). */
        private val AM_PM_SHORT = listOf(
            "am" to "pm", "पू" to "अ", "पू" to "अ", "સ" to "સા", "கா" to "மா", "രാ" to "വൈ", "ಪೂ" to "ಅ", "ఉ" to "సా",
        )

        fun amPmShort(language: PanchangLanguage, pm: Boolean): String = AM_PM_SHORT[language.ordinal].let { if (pm) it.second else it.first }

        internal fun monthsComplete(): Boolean = MONTHS.size == PanchangLanguage.entries.size && MONTHS.all { it.size == 12 }
    }
