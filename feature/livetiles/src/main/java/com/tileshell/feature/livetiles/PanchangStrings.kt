/** The language the Panchang tile, widget and hub are showing, for the composables that draw it. */
internal val LocalPanchangLanguage = compositionLocalOf { PanchangLanguage.DEFAULT }

/** The language the user chose for the Panchang (marathi until they pick one), following changes live. */
@Composable
internal fun rememberPanchangLanguage(): PanchangLanguage {
    val context = LocalContext.current
    val settings by PanchangPrefs.settings(context).collectAsState()
    return settings?.language ?: PanchangLanguage.DEFAULT
}

